"""Generate original soft electric-piano PCM assets; Python standard library only.

Run from any directory. Checked-in header is sufficient for normal firmware builds.
WAV previews go to the ignored build/audio-previews directory.
"""
import math
from pathlib import Path
import struct
import wave

ROOT = Path(__file__).resolve().parents[1]
RATE = 16000
MELODIES = {
    'Start': [(0, 392, .6), (.18, 493.88, .7)],
    'Completion': [(0, 392, .8), (.28, 493.88, .8),
                   (.56, 587.33, .9), (.95, 783.99, 1.0)],
}


def render(notes):
    samples = [0.] * round((max(start + duration for start, _, duration in notes) + .15) * RATE)
    for start, frequency, duration in notes:
        offset = round(start * RATE)
        for i in range(round(duration * RATE)):
            t = i / RATE
            phase = 2 * math.pi * frequency * t
            value = (math.sin(phase)
                     + .22 * math.sin(2 * phase) * math.exp(-t / .18)
                     + .07 * math.sin(3 * phase) * math.exp(-t / .08)) * math.exp(-t / .26)
            envelope = min(1, t / .009) * min(1, (duration - t) / .03)
            samples[offset + i] += .28 * value * envelope
    assert max(abs(value) for value in samples) < 1, 'PCM clipping'
    return [round(value * 32767) for value in samples]


def main():
    header = ['// Generated by tools/generate_piano_audio.py; original synthesized audio.',
              '#pragma once', '#include <stdint.h>', 'namespace PianoAudio {',
              f'constexpr uint32_t kSampleRate = {RATE};']
    preview = ROOT / 'build/audio-previews'
    preview.mkdir(parents=True, exist_ok=True)
    for name, notes in MELODIES.items():
        pcm = render(notes)
        header.append(f'const int16_t k{name}[] = {{')
        header.extend('  ' + ','.join(map(str, pcm[i:i + 24])) + ',' for i in range(0, len(pcm), 24))
        header.append('};')
        with wave.open(str(preview / f'piano-{name.lower()}.wav'), 'wb') as output:
            output.setnchannels(1)
            output.setsampwidth(2)
            output.setframerate(RATE)
            output.writeframes(struct.pack(f'<{len(pcm)}h', *pcm))
        print(f'{name}: {len(pcm)} samples, {len(pcm) / RATE:.2f}s')
    header.append('} // namespace PianoAudio')
    (ROOT / 'firmware/FlipPomodoroTimer/PianoAudio.h').write_text('\n'.join(header) + '\n', encoding='utf-8')


if __name__ == '__main__':
    main()
