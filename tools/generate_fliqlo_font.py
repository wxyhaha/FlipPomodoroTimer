"""Generate tall condensed bold sans-serif Fliqlo-style digit masks (64x132)."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

W, H = 64, 132
FONT_CANDIDATES = [
    r"C:\Windows\Fonts\ARIALNB.TTF",
    r"C:\Windows\Fonts\impact.ttf",
    r"C:\Windows\Fonts\arialbd.ttf",
]

def pick_font(size):
    for p in FONT_CANDIDATES:
        if Path(p).exists():
            return ImageFont.truetype(p, size)
    raise FileNotFoundError("No suitable condensed bold font found")

def render_digit(d, font, S=2):
    canvas = Image.new("L", (W * S, H * S), 0)
    draw = ImageDraw.Draw(canvas)
    ch = str(d)
    bbox = draw.textbbox((0, 0), ch, font=font)
    tw = bbox[2] - bbox[0]
    th = bbox[3] - bbox[1]
    ox = (W * S - tw) / 2 - bbox[0]
    oy = (H * S - th) / 2 - bbox[1]
    draw.text((ox, oy), ch, fill=255, font=font)
    img = canvas.resize((W, H), Image.Resampling.LANCZOS)
    px = img.load()
    return [px[x, y] for y in range(H) for x in range(W)]

def main():
    S = 2
    font = pick_font(int(134 * S))
    lines = [
        "// Generated by tools/generate_fliqlo_font.py; condensed bold Fliqlo digits.",
        "#pragma once",
        "#include <stdint.h>",
        f"static constexpr int FLIQLO_GLYPH_W = {W};",
        f"static constexpr int FLIQLO_GLYPH_H = {H};",
        f"static const uint8_t FLIQLO_DIGITS[10][{W * H}] = {{",
    ]
    for d in range(10):
        vals = render_digit(d, font, S)
        lines.append("  {")
        for y in range(0, W * H, W):
            lines.append("    " + ",".join(map(str, vals[y:y + W])) + ",")
        lines.append("  },")
    lines.append("};")
    target = Path(__file__).resolve().parents[1] / "firmware/FlipPomodoroTimer/FliqloFont.h"
    target.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"Generated {target} ({W}x{H} x 10)")

if __name__ == "__main__":
    main()
